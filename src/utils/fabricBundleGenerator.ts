import JSZip from 'jszip';
import { ProjectData } from '../types/migration';

export async function generateFabricBundle(project: ProjectData): Promise<Blob> {
  const zip = new JSZip();

  // Root README & metadata
  zip.file(
    'README.md',
    `# Microsoft Fabric Migration Bundle - ${project.name}
Generated by VectorLab Multi-Agent Migration Engine
Source Platform: ${project.platform.toUpperCase()}
Source File: ${project.sourceFile}
Target Architecture: Microsoft Fabric Direct Lake + Power BI PBIR + TMDL
Timestamp: ${new Date().toISOString()}

## Bundle Contents
1. /tmdl - Tabular Model Definition Language semantic model files
2. /pbi - Power BI Enhanced Report Format (PBIR) visual definitions
3. /lakehouse - Direct Lake Delta Lake table schemas (Bronze -> Silver -> Gold)
4. /qa - Quality Assurance reconciliation report and audit certificate
`
  );

  // TMDL directory
  const tmdlFolder = zip.folder('tmdl');
  if (tmdlFolder) {
    Object.entries(project.biEngineering.tmdlFiles).forEach(([filePath, content]) => {
      tmdlFolder.file(filePath, content);
    });
  }

  // PBIR directory
  const pbiFolder = zip.folder('pbi');
  if (pbiFolder) {
    pbiFolder.file(
      'definition.pbir',
      JSON.stringify(project.biEngineering.pbirDefinition, null, 2)
    );
    pbiFolder.file(
      'report.json',
      JSON.stringify(
        {
          name: project.name,
          version: '2.0.0',
          visualsCount: project.metadata.visualContainers.length,
          visualContainers: project.biEngineering.pbirDefinition.visualContainers,
        },
        null,
        2
      )
    );
  }

  // Lakehouse Delta schemas
  const lakehouseFolder = zip.folder('lakehouse');
  if (lakehouseFolder) {
    lakehouseFolder.file(
      'delta_schemas.json',
      JSON.stringify(project.biEngineering.deltaSchemas, null, 2)
    );
    lakehouseFolder.file(
      'direct_lake_manifest.json',
      JSON.stringify(
        {
          lakehouseName: project.biEngineering.deploymentTarget.lakehouse,
          workspace: project.biEngineering.deploymentTarget.workspace,
          sqlEndpoint: project.biEngineering.deploymentTarget.sqlEndpoint,
          strategy: project.convergence.directLakeStrategy,
          tables: project.biEngineering.deltaSchemas.map((s) => ({
            name: s.tableName,
            layer: s.layer,
            storage: s.storageUrl,
          })),
        },
        null,
        2
      )
    );
  }

  // QA Audit report
  const qaFolder = zip.folder('qa');
  if (qaFolder) {
    qaFolder.file(
      'reconciliation_audit.json',
      JSON.stringify(
        {
          certificateId: project.qualityAssurance.auditCertificateId,
          fidelityScore: project.qualityAssurance.overallFidelityScore,
          reconciliations: project.qualityAssurance.reconciliations,
          testSuite: project.qualityAssurance.testSuite,
          verifiedAt: project.qualityAssurance.timestamp,
        },
        null,
        2
      )
    );
  }

  return await zip.generateAsync({ type: 'blob' });
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = window.URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.style.display = 'none';
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  window.URL.revokeObjectURL(url);
  document.body.removeChild(a);
}
